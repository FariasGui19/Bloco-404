import assert from 'node:assert/strict';
import {map as praia} from '../js/data/worlds/arquipelago-rotas-perdidas/praia-inicial.js';
import {map as saguao} from '../js/data/worlds/hub-404/saguao.js';
import {map as controle} from '../js/data/worlds/arquipelago-rotas-perdidas/bio-sala-controle.js';
import {state} from '../js/game/state.js';
import {canStandAt, moveWithCollision} from '../js/game/collision.js';
import {CONFIG} from '../js/config.js';
import {climaVisivelNoMapa} from '../js/game/clima.js';
import {listTools, selectTool, getSelectedToolId} from '../js/game/tools.js';
import {toggleNucleoForm} from '../js/game/nucleo-form.js';
import {__wheelInternals} from '../js/ui/nucleo-wheel.js';
import {describeNextUnlock} from '../js/game/unlocks.js';
import {BIO_ULTIMATE_SHEETS, getBioUltimateFrame} from '../js/data/bio-ultimate-animation.js';
state.objects = praia.objects.map(o => ({...o,x:o.x+.5,y:o.y+.5}));
state.actors=[];
const spawn = praia.spawnPoints.vindo_do_trem;
assert(canStandAt(praia,spawn.x,spawn.y,CONFIG.PLAYER_RADIUS));
const player = {...spawn};
assert(moveWithCollision(praia,player,0,1,CONFIG.PLAYER_RADIUS));
assert(player.y > spawn.y + .8);
assert(climaVisivelNoMapa(praia));
assert(!climaVisivelNoMapa(saguao));
assert(!climaVisivelNoMapa(controle));
assert(!climaVisivelNoMapa({meta:{}}));
const progress={archetype:'nucleo_dez_forma',archetypeProgress:{nucleo_dez_forma:{level:1}},abilities:['forma_veloz'],tools:{nucleo_dez_forma:'nucleo_bruto'}};
const p={ability:{cooldowns:{}}};
assert.equal(getSelectedToolId(progress),null);
assert.equal(selectTool(progress,'nucleo_bruto'),null);
assert.equal(toggleNucleoForm(progress,p,'forma_bruta'),false);
assert.deepEqual(__wheelInternals.playableCards(progress).map(t=>t.id),['nucleo_veloz']);
progress.archetypeProgress.nucleo_dez_forma.level=3;
assert(listTools(progress).find(t=>t.id==='nucleo_bruto').locked);
assert.match(describeNextUnlock(progress),/QUEBRA SISTEMAS.*NÍVEL 4/);
assert.equal(toggleNucleoForm(progress,p,'forma_bruta'),false);
progress.archetypeProgress.nucleo_dez_forma.level=4;
assert.equal(getSelectedToolId(progress),'nucleo_bruto');
assert(!listTools(progress).find(t=>t.id==='nucleo_bruto').locked);
assert(toggleNucleoForm(progress,p,'forma_bruta'));
for (const [signature,sheet] of Object.entries(BIO_ULTIMATE_SHEETS)) {
  assert.equal(sheet.cols,4,signature);
  const frame=getBioUltimateFrame({archetype:'motor_bio_forja'},{ultimate:{charge:.2,chargeDefinition:{signature}}});
  assert(Number.isFinite(frame.scale) && frame.scale>0);
}
assert.equal(BIO_ULTIMATE_SHEETS.propulsores.scale,.52);
const rede = getBioUltimateFrame({archetype:'motor_bio_forja'},{ultimate:{charge:.1,chargeDuration:.42,chargeDefinition:{signature:'cabos'}}});
assert.equal(rede.col,1);
assert.equal(rede.offsetX,95*.57);
console.log('Chegada livre, clima exterior, progressão das formas e execução Bio OK.');
