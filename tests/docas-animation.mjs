import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DOCAS_MOTION_KEY,movimentoDocas,definirMovimentoDocas,movimentoDocasReduzido,avancarAnimacaoDocas,tempoVisualDocas} from '../js/engine/docas-animation.js';
let osReduce=true;const storage=new Map();
globalThis.matchMedia=()=>({matches:osReduce});
globalThis.localStorage={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v)};
assert.equal(movimentoDocas(),'normal');
assert.equal(movimentoDocasReduzido(),false,'OS cannot silently freeze default scene');
const state={progress:{mareCromatica:{iniciada:false,restante:600}},world:{isLoading:false}};
for(let i=0;i<20;i++)avancarAnimacaoDocas(state,.1);
assert(Math.abs(state.docasAnimation.elapsed-2)<1e-9,'100ms visual frames are not clamped to the 33ms physics step');
assert.equal(state.progress.mareCromatica.restante,600);
assert.equal(state.docasAnimation.frames,20);
const a=tempoVisualDocas(state,100000);assert.equal(a.t,state.docasAnimation.elapsed);assert.equal(a.clock,a.t);
const before=state.docasAnimation.elapsed;
avancarAnimacaoDocas(state,4,true);assert.equal(state.docasAnimation.elapsed,before);
avancarAnimacaoDocas(state,NaN);avancarAnimacaoDocas(state,-1);assert.equal(state.docasAnimation.elapsed,before);
avancarAnimacaoDocas(state,4);assert.equal(state.docasAnimation.elapsed,before+.25,'bounded resume delta');
definirMovimentoDocas('reduzido');assert.deepEqual(tempoVisualDocas(state),{reduced:true,t:0,clock:null});
avancarAnimacaoDocas(state,.1);assert(state.docasAnimation.elapsed>before+.25,'preference freezes pose, not underlying RAF clock');
assert.equal(storage.get(DOCAS_MOTION_KEY),'reduzido');
definirMovimentoDocas('sistema');assert(movimentoDocasReduzido());osReduce=false;assert(!movimentoDocasReduzido());
definirMovimentoDocas('normal');assert.equal(tempoVisualDocas({},1500).t,1.5,'isolated renderer API remains compatible');
assert.throws(()=>definirMovimentoDocas('invalid'),TypeError);
const main=readFileSync('js/main.js','utf8'),frame=main.slice(main.indexOf('async function frame(now)'));
assert(frame.indexOf('avancarAnimacaoDocas(')<frame.indexOf('await update(dt)'),'visual clock precedes all simulation early returns');
assert(frame.includes('render(map, state, now)'));
const renderer=readFileSync('js/engine/docas-view.js','utf8');
assert(renderer.includes('tempoVisualDocas(state,now)'));
assert(!renderer.includes('prefers-reduced-motion'),'single explicit motion policy for dock layers');
console.log('Docas: RAF clock independent of mission/calibration, raw visual delta, explicit motion modes and OS opt-in OK.');
