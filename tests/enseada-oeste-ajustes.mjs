import assert from 'node:assert/strict';
import { map } from '../js/data/worlds/arquipelago-rotas-perdidas/enseada-ecos.js';
import { createCoastalFauna } from '../js/game/fauna-costeira.js';
import { pocaEm } from '../js/engine/pocas.js';
const obj = id => { const o = map.objects.find(o => o.id === id); assert(o, id); return o; };
const piscina = obj('piscina_mare_viva_enseada');
const capivara = createCoastalFauna(map).find(a => a.id === 'enseada_capivara');
assert(capivara, 'capivara deve ser criada pela fauna real');
assert(Math.hypot(capivara.x-piscina.x, capivara.y-piscina.y) < 1.3, 'capivara dentro da piscina');
assert(piscina.x + piscina.y + 1 + piscina.depthOffset < capivara.x + capivara.y, 'piscina desenhada antes da capivara');
const poca = map.pocas.find(p => p.id === 'poca_cascata_enseada');
assert(poca.treino && poca.ocultarMarcador && pocaEm(map,poca.x,poca.y), 'treino permanece funcional sem marcador visual');
assert.equal(map.trainingTargets.length, 0, 'eco de treino retirado do quadrante');
assert.equal(obj('fonte_termal_enseada').renderizar, false, 'poço extra oculto');
const gruta = obj('gruta_concha_enseada'), espelho = obj('espelho_arquetipos_enseada');
assert.equal(gruta.sprite, 'enseada_gruta_oeste');
assert(gruta.x-gruta.y < espelho.x-espelho.y && gruta.x+gruta.y < espelho.x+espelho.y);
assert.equal(obj('concha_praia_central_enseada').sprite, 'enseada_concha_perola_oeste');
assert(obj('cristais_corais_gruta_oeste').x-obj('cristais_corais_gruta_oeste').y > gruta.x-gruta.y);
console.log('Oeste: capivara, piscina, gruta e remoção visual do treino OK.');
