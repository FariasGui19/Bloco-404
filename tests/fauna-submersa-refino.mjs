import assert from 'node:assert/strict';
import { map } from '../js/data/worlds/arquipelago-rotas-perdidas/praia-inicial.js';
import { getVidaAquatica } from '../js/game/vida-aquatica.js';
import { criarBichosFeridos, detalhesFauna, socorrerProximo, podeAjudar } from '../js/game/fauna-ferida.js';
const recifes = getVidaAquatica(map).recifes;
const antigos = criarBichosFeridos(map, recifes, {limite:4});
const ampliados = criarBichosFeridos(map, recifes, {limite:5});
assert.deepEqual(ampliados.slice(0, antigos.length).map(b=>b.id), antigos.map(b=>b.id), 'saves antigos mantêm seus animais');
const cavalo = ampliados.find(b=>b.tipo==='cavalo_marinho');
assert.ok(cavalo, 'novo animal em um recife acessível');
assert.ok('YyDdX'.includes(map.aguaPraia[Math.floor(cavalo.y)][Math.floor(cavalo.x)]));
assert.equal(podeAjudar(cavalo,'mare_astral',false).ok,false);
assert.equal(podeAjudar(cavalo,'mare_astral',true).ok,true);
const novos = criarBichosFeridos(map, recifes, {limite:6});
assert.deepEqual(novos.slice(0, ampliados.length).map(b=>b.id), ampliados.map(b=>b.id));
assert.ok(novos.some(b=>b.tipo==='peixe_palhaco'));
const progress = {};
const cache = detalhesFauna(map, progress, recifes);
const alvo = cache.find(b=>b.id===cavalo.id);
assert.ok(alvo);
const ctx = {player:{x:alvo.x,y:alvo.y}, progress, arquetipo:'mare_astral', submerso:true, recifes};
const res = socorrerProximo(map,ctx);
assert.equal(res?.tipo,'cavalo_marinho'); assert.ok(res.xp>0 && res.respeito>0);
assert.ok(progress.faunaTratada[alvo.id]);
assert.ok(progress.archetypeProgress.mare_astral.level > 1 || progress.archetypeProgress.mare_astral.xp > 0, 'socorro concede XP');
assert.equal(socorrerProximo(map,ctx), null, 'não paga o socorro duas vezes');
assert.equal(detalhesFauna(map,progress,recifes).find(b=>b.id===alvo.id).estado,'curado');
const peixe = cache.find(b => b.tipo === 'peixe_palhaco');
assert.ok(peixe);
const resPeixe = socorrerProximo(map, {...ctx, player:{x:peixe.x,y:peixe.y}});
assert.equal(resPeixe?.tipo, 'peixe_palhaco');
assert.ok(progress.faunaTratada[peixe.id]);
console.log('Fauna submersa: IDs anteriores, novo socorro e persistência OK.');
