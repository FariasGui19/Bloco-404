import assert from 'node:assert/strict';
import { ImmersiveViewManager, IMMERSIVE_MODE } from '../js/game/immersive-view-manager.js';
const state = { world: { currentMapId: 'ilha_enseada_ecos' }, player: { x: 7, y: 9, facing: 'down', health: 40, maxHealth: 100, energy: 5, maxEnergy: 100, target: { x: 8 }, moving: false } };
const camera = { x: 10, y: 20, zoom: .8, targetZoom: .9, follow: false };
const originalCamera = { ...camera }, originalPos = { x: state.player.x, y: state.player.y };
let visits = 0, pending = 0, clears = 0;
const m = new ImmersiveViewManager({ state, camera, clearInput: () => clears++, visit: () => visits++ });
const input = { pressed: new Set() }, step = (n = 1) => { for (let i=0;i<n;i++) m.update(.1,input); };
assert.equal(m.begin({ id: 'inexistente', x: 8, y: 9 }), false);
assert(m.begin({ id: 'piscina_mare_viva_enseada', x: 8, y: 9 }));
assert(m.active && state.world.immersiveActive);
assert(!m.begin({ id: 'gruta_concha_enseada', x: 8, y: 9 }));
step(8); assert.equal(m.mode, IMMERSIVE_MODE.FIRST_PERSON_DIORAMA); assert.equal(visits, 1);
m.look(0, 0, 100, 100); step(1); assert(m.lookX < 0 && m.lookY < 0);
m.action(1); assert(m.petTime > 0); m.action(2); assert(m.relaxing);
const health = state.player.health, energy = state.player.energy; step(20);
assert(state.player.health > health && state.player.energy > energy);
assert(state.player.health <= state.player.maxHealth && state.player.energy <= state.player.maxEnergy);
input.pressed.add('escape'); m.update(.01,input); input.pressed.clear(); step(6);
assert.equal(m.mode, IMMERSIVE_MODE.ISOMETRIC); assert.deepEqual(camera, originalCamera);
assert.deepEqual({ x: state.player.x, y: state.player.y }, originalPos);
assert.equal(state.player.moving, false); assert(!state.world.immersiveActive); assert(clears >= 2);
assert(m.begin({ id: 'gruta_concha_enseada', x: 8, y: 9 }));
step(2); input.pressed.add('escape'); m.update(.01,input); input.pressed.clear(); step(6);
assert.equal(visits, 1, 'cancelar entrada não concede visita'); assert.deepEqual(camera, originalCamera);
assert(m.begin({ id: 'gruta_concha_enseada', x: 8, y: 9 })); step(8); assert.equal(visits, 2);
input.pressed.add('e'); m.update(.01,input); input.pressed.clear(); step(6); assert(!m.active);
assert(m.begin({ id: 'totem_eco_enseada', x: 8, y: 9 }, () => pending++)); step(6);
assert.equal(pending, 1); assert(!m.active); assert.deepEqual(camera, originalCamera);
assert(m.begin({ id: 'totem_eco_enseada', x: 8, y: 9 }, () => pending++));
input.pressed.add('escape'); m.update(.01,input); input.pressed.clear(); assert.equal(pending, 1);
state.world.currentMapId = 'outro'; assert.equal(m.begin({ id: 'piscina_mare_viva_enseada' }), false);
console.log('Imersão: entrada, cancelamento, câmera, ações, recuperação e retorno OK.');
