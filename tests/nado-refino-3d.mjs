import assert from 'node:assert/strict';
import { cameraLivre } from '../js/engine/perspectiva-submersa.js';
import { iniciarVoo, atualizarVoo } from '../js/game/nado-voo.js';
import { criarEstadoNado, atualizarNado, derivadosDoRespeito } from '../js/game/nado.js';
import { criarArvore } from '../js/game/nado-arvore.js';
import { createCoastField } from '../js/engine/coast-field.js';
const rows = ['SSSSSSSSS','SDDDDDDDS','SDDDDDDDS','SDDDDDDDS','SDDDDDDDS','SDDDDDDDS','SDDDDDDDS','SDDDDDDDS','SSSSSSSSS'];
const map = { id:'refino', aguaPraia:rows, aguaSobPontes:true };
const livre = cameraLivre(map, 1.5, 4.5, .1, 4.5);
assert.ok(livre.x > 1, 'câmera recua antes da parede');
assert.deepEqual(cameraLivre(map, 3.5, 4.5, 5.5, 4.5), {x:5.5,y:4.5});
assert.deepEqual(cameraLivre(map, .5, -.1, .5, -2), {x:.5,y:-2}, 'mar visual além da borda');
const n = criarEstadoNado(); Object.assign(n,{ativo:true,submerso:true,mareAstral:true,profundidade:1.8,ar:2,dirX:1,dirY:0});
const voo = iniciarVoo(n);
const curva = atualizarVoo(voo,{direita:true},.05);
assert.ok(curva.y > 0 && !curva.ativo, 'girar não acelera sozinho');
assert.ok(atualizarVoo(voo,{descer:true},.05).ativo, 'W impulsiona');
assert.ok(!atualizarVoo(voo,{subir:true},.05).ativo, 'subir não acelera');
const field=createCoastField(rows,8), arvore=criarArvore(3);
const ctx={map,x:4.5,y:4.5,field,arvore,dt:.05,mareAstral:true,mergulhoLivre:true,mergulhar:false};
const antes=n.ar; atualizarNado(n,ctx);
assert.ok(n.submerso && n.ar < antes, 'continua gastando ar até emergir');
n.ar=.01; n.profundidade=1.8;
let eventos=0;
for(let i=0;i<60;i++) { const r=atualizarNado(n,ctx); if(r.engoliuAgua) eventos++; }
assert.equal(eventos,1,'sem ar aplica susto apenas uma vez');
assert.ok(n.profundidade < 1.25 && n.ar > 0, 'sobe e recupera fôlego');
const inicial=derivadosDoRespeito({valor:0}), experiente=derivadosDoRespeito({valor:1});
assert.ok(experiente.ar>inicial.ar && experiente.velocidade>inicial.velocidade && experiente.arrancada>inicial.arrancada);
console.log('Câmera, controles, fôlego e progressão submersa OK.');
