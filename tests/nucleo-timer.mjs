import assert from 'node:assert/strict';
import { toggleNucleoForm, updateNucleoForm, NUCLEO_FORM_DURATION, NUCLEO_FORM_RECHARGE } from '../js/game/nucleo-form.js';
const progress = { archetype: 'nucleo_dez_forma', abilities: ['forma_veloz'] };
const player = { ability: {} };
assert(toggleNucleoForm(progress, player));
assert.equal(player.nucleoRuntime.remaining, NUCLEO_FORM_DURATION);
updateNucleoForm(progress, player, 3);
assert.equal(player.nucleoRuntime.remaining, NUCLEO_FORM_DURATION, 'transição não consome tempo');
player.ability.effect = null;
updateNucleoForm(progress, player, 29);
assert.equal(player.nucleoForm, 'forma_veloz');
player.ability.dash = {};
updateNucleoForm(progress, player, 2);
assert.equal(player.nucleoForm, 'forma_veloz', 'não retorna no meio do dash');
player.ability.dash = null;
updateNucleoForm(progress, player, .1, false);
assert.equal(player.nucleoForm, 'forma_veloz', 'aguarda ponto seguro');
updateNucleoForm(progress, player, .1, true);
assert.equal(player.nucleoForm, null);
assert.equal(player.nucleoRuntime.recharge, NUCLEO_FORM_RECHARGE);
assert(!toggleNucleoForm(progress, player));
player.ability.effect = null;
updateNucleoForm(progress, player, 7);
assert(!toggleNucleoForm(progress, player));
updateNucleoForm(progress, player, 1);
assert(toggleNucleoForm(progress, player), 'recarga libera a seleção');
console.log('Núcleo: duração, travessia segura e recarga OK.');
