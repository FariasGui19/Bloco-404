import assert from 'node:assert/strict';
import { CONFIG } from '../js/config.js';
import { state } from '../js/game/state.js';
import { input } from '../js/engine/input.js';
import { getPlayerMoveSpeed, updatePlayer, VELOZ_SPEED_MULTIPLIER } from '../js/game/player.js';
import { getBasicAttackPose } from '../js/data/basic-attack-poses.js';
import { toggleNucleoForm, updateNucleoForm, NUCLEO_FORM_DURATION } from '../js/game/nucleo-form.js';

const map = { layout: Array.from({ length: 12 }, () => Array(12).fill(0)) };
state.world.currentMap = map; state.objects = []; state.actors = [];
const p = state.player;
state.progress = { archetype: 'nucleo_dez_forma', abilities: ['forma_veloz'], flags: {} };
Object.assign(p, { x: 5, y: 5, target: null, nucleoForm: null, nucleoRuntime: null, ability: {} });
assert.equal(getPlayerMoveSpeed(state.progress, p), CONFIG.PLAYER_SPEED);
input.keys.d = true; updatePlayer(.1); const base = Math.hypot(p.x - 5, p.y - 5);
assert(toggleNucleoForm(state.progress, p)); p.ability.effect = null;
p.x = p.y = 5; updatePlayer(.1); const fast = Math.hypot(p.x - 5, p.y - 5);
assert(Math.abs(fast / base - VELOZ_SPEED_MULTIPLIER) < 1e-8, 'teclado acelera apenas na forma');
input.keys.d = false; p.x = p.y = 5; p.target = { x: 9, y: 5 }; updatePlayer(.1);
assert(Math.abs(p.x - 5 - CONFIG.PLAYER_SPEED * VELOZ_SPEED_MULTIPLIER * .1) < 1e-8, 'alvo por clique usa mesma velocidade');
map.layout[5][7] = 1; p.x = 6; p.y = 5.5; p.target = { x: 9, y: 5.5 }; updatePlayer(.4);
assert(p.x <= 7 - CONFIG.PLAYER_RADIUS + 1e-9, 'subpassos preservam colisão com parede');
map.layout[5][7] = 0; p.ability.effect = null;
updateNucleoForm(state.progress, p, NUCLEO_FORM_DURATION, true);
assert.equal(getPlayerMoveSpeed(state.progress, p), CONFIG.PLAYER_SPEED, 'velocidade normal após expirar');
assert.equal(getPlayerMoveSpeed({archetype:'mare_astral'}, {nucleoForm:'forma_veloz'}), CONFIG.PLAYER_SPEED);
const attack = (style, suit, facing, fraction = .5) => ({ equippedSuit: suit, facing, ability: {}, combat: { style, duration: .32, timeLeft: .32 * (1 - fraction) } });
let dom = attack('lamina_dominio_anciao', 'dominio', 'right');
let pose = getBasicAttackPose({archetype: 'lamina_dominio_anciao'}, dom);
assert.equal(pose.sprite, 'player_dominio_lvl1'); assert.equal(pose.col, 3); assert(!pose.flip);
dom.facing = 'left'; assert(getBasicAttackPose({archetype: 'lamina_dominio_anciao'}, dom).flip);
dom.facing = 'up'; assert.equal(getBasicAttackPose({archetype: 'lamina_dominio_anciao'}, dom), null);
dom.facing = 'right'; dom.equippedSuit = null; assert.equal(getBasicAttackPose({archetype: 'lamina_dominio_anciao'}, dom), null);
const bio = attack('motor_bio_forja', 'bio_forja', 'left');
assert.equal(getBasicAttackPose({archetype:'motor_bio_forja'}, bio).col, 3);
bio.facing = 'right'; assert(getBasicAttackPose({archetype:'motor_bio_forja'}, bio).flip);
bio.ability.effect = {id:'bio_dash', timeLeft:.1}; assert.equal(getBasicAttackPose({archetype:'motor_bio_forja'}, bio), null);
assert.equal(getBasicAttackPose({archetype:'mare_astral'}, attack('mare_astral', 'mare', 'right')), null, 'não troca para arte de outro nível');
console.log('Forma veloz: locomoção e colisão; poses básicas e prioridade de habilidades OK.');
