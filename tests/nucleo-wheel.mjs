import assert from 'node:assert/strict';
import { input } from '../js/engine/input.js';
import { openNucleoWheel, isNucleoWheelOpen, updateNucleoWheel } from '../js/ui/nucleo-wheel.js';
let visible = false;
const button = { addEventListener(event, fn) { this[event] = fn; }, focus() {} };
const overlay = { innerHTML: '', classList: { add() { visible = true; }, remove() { visible = false; } }, querySelector() { return button; }, addEventListener() {} };
globalThis.document = { createElement() { return overlay; }, body: { appendChild() {} } };
const player = { ability: { dash: null } };
assert(!openNucleoWheel({archetype:'mare_astral'}, player));
assert(!openNucleoWheel({archetype:'nucleo_dez_forma'}, {ability:{dash:{}}}));
const progress = { archetype:'nucleo_dez_forma', abilities: ['forma_veloz', 'eco_scan'] };
assert(openNucleoWheel(progress,player));
assert(isNucleoWheelOpen() && visible);
input.pressed.add('escape'); updateNucleoWheel(); input.pressed.clear();
assert(!isNucleoWheelOpen() && !visible);
assert(openNucleoWheel(progress,player));
button.click();
assert(!isNucleoWheelOpen());
assert.deepEqual(progress.abilities, ['forma_veloz','eco_scan']);
assert.equal(player.equippedSuit, undefined);
console.log('Núcleo: abertura, cancelamento, confirmação e isolamento OK.');
