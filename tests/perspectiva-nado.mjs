import assert from 'node:assert/strict';
import { iniciarVoo, atualizarVoo } from '../js/game/nado-voo.js';
import { criarEstadoNado, moverNaAgua } from '../js/game/nado.js';
import { state } from '../js/game/state.js';
import { tryArchetypePower } from '../js/game/archetype-powers.js';
import { beginUltimate } from '../js/game/ultimate.js';
const n = criarEstadoNado();
Object.assign(n, {ativo:true, mareAstral:true, nivel:3, profundidade:1.8, dirX:1, dirY:0});
const voo = iniciarVoo(n);
for (let i=0;i<20;i++) atualizarVoo(voo, {direita:true, descer:true}, .05);
assert.ok(voo.heading > 1 && voo.roll < 0 && voo.pitch > 0 && voo.profundidadeAlvo === 2);
let dir; for (let i=0;i<30;i++) dir = atualizarVoo(voo, {subir:true}, .05);
assert.ok(dir.subir && voo.profundidadeAlvo <= 1.3);
Object.assign(n, {vx:0,vy:0,corrente:{x:0,y:0}});
moverNaAgua(n, .1, 1, 0, 4); const vx=n.vx;
moverNaAgua(n, .1, 0, 1, 4); assert.ok(n.vx > 0 && n.vx < vx && n.vy > 0, 'inércia na curva');
state.progress = {archetype:'mare_astral', abilities:['passo_corrente','senso_corrente'], flags:{}, inventory:[]};
state.world.currentMap = {id:'teste', aguaPraia:['DDD','DDD','DDD']};
state.player = {x:1,y:1,nado:n, energy:100, ability:{cooldowns:{}}, fragmentosMare:[{id:'eco',x:2,y:1}]};
Object.assign(n,{profundidade:.6,submerso:false,recargaArrancada:0,naPoca:false,medo:false});
let msg=''; tryArchetypePower('passo_corrente', m=>msg=m);
assert.ok(n.arrancada > 0 && !state.player.ability.dash && msg.includes('SUPERFÍCIE'));
tryArchetypePower('senso_corrente', m=>msg=m);
assert.equal(state.player.ability.sonarAquatico.x,2);
state.progress.archetype='nucleo_x10'; const energia=state.player.energy;
tryArchetypePower('forma_veloz',m=>msg=m);
assert.ok(msg.includes('TERRESTRE')); assert.equal(state.player.energy,energia);
assert.equal(beginUltimate({player:state.player,progress:state.progress}), false);
console.log('Perspectiva: controles, inércia e habilidades na água OK.');
