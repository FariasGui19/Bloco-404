from pathlib import Path
from PIL import Image
import numpy as np,json,hashlib
root=Path(__file__).resolve().parents[1];src=root/'assets/source-art/docas-exterior-lote8';out=root/'assets/sprites/docas-exterior-lote8';out.mkdir(parents=True,exist_ok=True);records=[]
for path in sorted(src.glob('*.png')):
 im=Image.open(path).convert('RGBA')
 # The notice source repeated its view; retain one complete board only.
 if path.stem=='aviso-vigia':im=im.crop((0,0,im.width//2,im.height))
 a=np.array(im);rgb=a[:,:,:3].astype(float)
 # Magenta matte, preserving black cables and the dark puddle.
 excess=np.minimum(rgb[:,:,0],rgb[:,:,2])-rgb[:,:,1];alpha=np.clip((60-excess)/25,0,1)
 a[:,:,3]=(a[:,:,3]*alpha).astype('uint8');partial=alpha<.99
 for ch in [0,2]:a[:,:,ch]=np.where(partial,np.minimum(a[:,:,ch],a[:,:,1]),a[:,:,ch])
