#!/usr/bin/env python3
"""Key three newly generated, reference-guided assets into one RGBA atlas.
No resampling of the protected lighthouse/portal or pre-existing atlas.
Dependencies: Pillow, NumPy. Reproducible; source art stays in source-art.
"""
from pathlib import Path
import json, hashlib
import numpy as np
from PIL import Image, ImageFilter, ImageDraw
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'assets/source-art/docas-fechamento'
OUT=ROOT/'assets/sprites/docas-fechamento'
NAMES=['casinha-esquerda','encosta-viva','margem-rochosa']

def key(path,interior=False):
 a=np.array(Image.open(path).convert('RGBA'));rgb=a[:,:,:3].astype(float)
 excess=rgb[:,:,1]-np.maximum(rgb[:,:,0],rgb[:,:,2])
 alpha=np.where(rgb[:,:,1]>110,np.clip((95-excess)/65,0,1),1)
 partial=alpha<.99
 a[:,:,1]=np.where(partial,np.minimum(a[:,:,1],np.maximum(a[:,:,0],a[:,:,2])),a[:,:,1])
 a[:,:,3]=(a[:,:,3].astype(float)*alpha).astype('uint8')
 if interior:
  # A green-key doorway must become a dark interior, not a sea-shaped hole.
  bg=Image.fromarray(np.where(a[:,:,3]<5,0,255).astype('uint8')).copy()
  ImageDraw.floodfill(bg,(0,0),128,thresh=0)
  enclosed=(np.array(bg)==0)&(a[:,:,3]<5)
  a[enclosed]=[11,19,28,255]
 a[a[:,:,3]==0]=0
 im=Image.fromarray(a)
 box=im.getchannel('A').point(lambda n:255 if n>15 else 0).getbbox()
 return im.crop(box),list(box)

def main():
 OUT.mkdir(parents=True,exist_ok=True)
 atlas=Image.new('RGBA',(2048,1280));x=8;y=8;row=0;frames={}
 for name in NAMES:
  im,box=key(SRC/(name+'.png'),name=='casinha-esquerda')
  im.thumbnail((1024,520),Image.Resampling.LANCZOS)
  w,h=im.size
  if x+w+8>2048:x=8;y+=row+16;row=0
  if y+h+8>1280:raise ValueError('atlas overflow')
  atlas.alpha_composite(im,(x,y))
  frames[name]={'rect':[x,y,w,h],'sourceCrop':box,'sourceSha256':hashlib.sha256((SRC/(name+'.png')).read_bytes()).hexdigest()}
  x+=w+16;row=max(row,h)
 atlas=atlas.crop((0,0,2048,y+row+8));a=np.array(atlas);a[a[:,:,3]==0]=0
 Image.fromarray(a).save(OUT/'atlas.png',optimize=True)
 manifest={'version':1,'provenance':'Three newly AI-generated assets guided by the supplied harbor reference; chroma keyed and independently anchored.','size':list(atlas.size),'frames':frames}
 (OUT/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
 (ROOT/'js/data/worlds/arquipelago-rotas-perdidas/docas-fechamento.js').write_text('// Generated by tools/preparar-docas-fechamento.py.\nexport const FRAMES_FECHAMENTO='+json.dumps(frames)+';\n')
 print('Fechamento: three generated sources, one RGBA atlas, no protected asset writes.')
if __name__=='__main__':main()
