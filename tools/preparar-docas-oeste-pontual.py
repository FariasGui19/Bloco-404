#!/usr/bin/env python3
"""Split the reference-guided western nook into depth-sorted RGBA layers.
Never edits world geometry or an existing atlas. Requires Pillow and NumPy.
"""
from pathlib import Path
import importlib.util,json,hashlib
import numpy as np
from PIL import Image,ImageDraw,ImageChops
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'assets/source-art/docas-oeste-pontual/composicao.png';OUT=ROOT/'assets/sprites/docas-oeste-pontual';OUT.mkdir(parents=True,exist_ok=True)
spec=importlib.util.spec_from_file_location('keyer',ROOT/'tools/preparar-docas-fechamento.py');k=importlib.util.module_from_spec(spec);spec.loader.exec_module(k)
im,box=k.key(SRC,False)
size=Image.open(SRC).size
full=Image.new('RGBA',size);full.paste(im,box[:2])
# The generator's bottom edge contains cropped foreground ground. Turn it
# into an irregular feathered wet shoreline instead of an opaque rectangle.
a=np.array(full);yy,xx=np.mgrid[:size[1],:size[0]]
edge=809+12*np.sin(xx/137)+7*np.sin(xx/51)
fade=np.clip((edge-yy)/42,0,1);fade=fade*fade*(3-2*fade)
fade*=np.clip(xx/9,0,1)
a[:,:,3]=(a[:,:,3]*fade).astype('uint8');a[a[:,:,3]==0]=0;full=Image.fromarray(a)
# Coordinates are authored on the generated 1216x864 source, not on the map.
# Higher priority objects own overlap pixels: porch, crystal, palms, dead tree.
polys={
 'cerca':[(893,658),(1050,630),(1216,725),(1216,840),(1136,821),(1080,789),(999,778),(947,756),(908,761),(901,734)],
 'abrigo':[(702,525),(976,466),(1046,502),(1070,525),(1050,548),(1050,640),(1095,642),(1110,668),(1216,722),(1216,838),(1136,821),(1080,789),(999,778),(947,756),(908,761),(901,734),(841,724),(802,707),(743,700),(720,667),(715,580)],
 'cristais':[(510,475),(651,446),(699,478),(715,544),(736,616),(743,666),(792,700),(765,752),(640,753),(535,729),(490,684),(492,600)],
 'palmeiras':[(280,355),(440,310),(457,230),(544,186),(650,184),(730,258),(720,377),(639,443),(603,520),(577,653),(509,705),(458,678),(416,550),(329,550),(280,490)],
 'arvore':[(700,0),(1216,0),(1216,456),(1080,530),(848,526),(762,432),(742,350),(700,230)],
}
assert size==(1216,864),'Regeneration requires reviewing the source masks.'
claimed=Image.new('L',size);parts={}
for name,poly in polys.items():
 mask=Image.new('L',size);ImageDraw.Draw(mask).polygon(poly,fill=255)
 mask=ImageChops.subtract(mask,claimed);claimed=ImageChops.lighter(claimed,mask)
 layer=full.copy();layer.putalpha(ImageChops.multiply(full.getchannel('A'),mask));parts[name]=layer
base=full.copy();base.putalpha(ImageChops.subtract(full.getchannel('A'),ImageChops.multiply(full.getchannel('A'),claimed)));parts['solo']=base
atlas=Image.new('RGBA',(2048,2048));x=y=8;row=0;frames={}
for name,layer in parts.items():
 bounds=layer.getchannel('A').getbbox();part=layer.crop(bounds);w,h=part.size
 if x+w+8>2048:x=8;y+=row+16;row=0
 assert y+h+8<=2048
 atlas.alpha_composite(part,(x,y));frames[name]={'rect':[x,y,w,h],'sourceBox':list(bounds)}
 x+=w+16;row=max(row,h)
atlas=atlas.crop((0,0,2048,y+row+8));a=np.array(atlas);a[a[:,:,3]==0]=0;Image.fromarray(a).save(OUT/'atlas.png',optimize=True)
manifest={'sourceSha256':hashlib.sha256(SRC.read_bytes()).hexdigest(),'sourceSize':list(size),'size':list(atlas.size),'frames':frames}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
(ROOT/'js/data/worlds/arquipelago-rotas-perdidas/docas-oeste-pontual.js').write_text('// Generated by tools/preparar-docas-oeste-pontual.py. Presentation only.\nexport const OESTE_PONTUAL_FRAMES='+json.dumps(frames)+';\n')

# The rear-cabin source contains the old dead tree on its left. Mask that
# overlap at NATIVE resolution, preserving every other source pixel exactly.
# This avoids global resampling changes from clipping its scaled bitmap.
REGIAO=[(85,344),(155,300),(212,270),(310,235),(348,205),(518,205),(526,274),(488,316),(463,334),(463,458),(479,485),(432,535),(280,535),(170,518),(78,485)]
old_path=ROOT/'assets/sprites/docas-fidelidade/fundos-enraizados.png'
old=Image.open(old_path).convert('RGBA');w,h=old.size
mask=Image.new('L',(w*4,h*4));ImageDraw.Draw(mask).polygon([((x-374)*w/480*4,(y-142)*h/258*4) for x,y in REGIAO],fill=255)
mask=mask.resize((w,h),Image.Resampling.LANCZOS)
a=np.array(old);a[:,:,3]=(a[:,:,3].astype(float)*(1-np.array(mask)/255)).round().astype('uint8');a[a[:,:,3]==0]=0
Image.fromarray(a).save(OUT/'fundos-preservados.png',optimize=True)
manifest['scope']=REGIAO;manifest['preservedSourceSha256']=hashlib.sha256(old_path.read_bytes()).hexdigest()
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')

print('Western nook: one new source, six depth layers, atlas and native masked rear image.')
