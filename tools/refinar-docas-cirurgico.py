#!/usr/bin/env python3
"""One additional atlas, only for five soft cutouts and the missing east apron.
Run preparar-docas-encaixe.py first to reset base atlases. Re-running this pass
is idempotent. Native reference RGB + original silhouette alpha; no invented
super-resolution detail. Pillow and NumPy required.
"""
from pathlib import Path
import json
from PIL import Image, ImageDraw, ImageFilter, ImageChops
import numpy as np
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/sprites/docas-encaixe'
NAMES=['cabana-oeste','galpao','anexo-cais','caixa-c','barril-c']

def main():
 m=json.loads((OUT/'manifest.json').read_text())
 base=m.get('baseFrames') or {name:dict(m['frames'][name]) for name in NAMES}
 source=Image.open(ROOT/m['source']).convert('RGB');kx=source.width/1568;ky=source.height/882
 atlas=Image.new('RGBA',(2048,2048));cx=8;cy=8;rowh=0
 def pack(name,rgb,alpha,frame):
  nonlocal cx,cy,rowh
  rgb=rgb.convert('RGBA');rgb.putalpha(alpha);w,h=rgb.size
  if cx+w+8>2048:cx=8;cy+=rowh+16;rowh=0
  if cy+h+8>2048:raise ValueError('Atlas overflow')
  atlas.alpha_composite(rgb,(cx,cy))
  m['frames'][name]={**frame,'sheet':'refino','rect':[cx,cy,w,h],'density':2}
  cx+=w+16;rowh=max(rowh,h)
 for name,p in base.items():
  x,y,w,h=p['plant'];ox,oy={'caixa-c':(0,-84),'barril-c':(0,-55)}.get(name,(0,0))
  sx,sy=x-ox,y-oy
  native_box=(sx*kx,sy*ky,(sx+w)*kx,(sy+h)*ky)
  rgb=source.transform((w*2,h*2),Image.Transform.EXTENT,native_box,Image.Resampling.BICUBIC)
  rgb=rgb.filter(ImageFilter.UnsharpMask(radius=.65,percent=75,threshold=3))
  old=Image.open(OUT/(p['sheet']+'.png'));u,v,uw,vh=p['rect']
  alpha=old.getchannel('A').crop((u,v,u+uw,v+vh)).resize((w*2,h*2),Image.Resampling.LANCZOS)
  pack(name,rgb,alpha,{**p,'sourcePlant':[sx,sy,w,h]})
 # Ground only: apron/rock contact behind the annex and watchtower. The
 # structures are subtracted, so there are no baked duplicate roofs or walls.
 poly=[(946,565),(977,548),(1018,535),(1080,522),(1146,518),(1200,523),(1252,518),(1297,494),(1344,485),(1380,500),(1390,526),(1370,548),(1320,566),(1274,583),(1222,601),(1165,620),(1100,632),(1040,619),(992,603),(960,589)]
 box=(940,480,1396,638);x,y,x2,y2=box;w,h=x2-x,y2-y
 mask=Image.new('L',(1568,882));ImageDraw.Draw(mask).polygon(poly,fill=255)
 mask=mask.filter(ImageFilter.MinFilter(5)).filter(ImageFilter.GaussianBlur(2))
 for name,p in m['frames'].items():
  if p['layer']!='object':continue
  original=base.get(name,p);u,v,uw,vh=original['rect']
  old=Image.open(OUT/(original['sheet']+'.png')).getchannel('A').crop((u,v,u+uw,v+vh))
  px,py,pw,ph=original.get('sourcePlant',original['plant'])
  # The three translated props are not part of this source-ground region.
  if name in ['caixa-c','barril-c','cristal-c']:continue
  temp=Image.new('L',mask.size);temp.paste(old.resize((pw,ph)),(px,py));mask=ImageChops.subtract(mask,temp)
 rgb=source.transform((w*2,h*2),Image.Transform.EXTENT,(x*kx,y*ky,x2*kx,y2*ky),Image.Resampling.BICUBIC)
 alpha=mask.crop(box).resize((w*2,h*2),Image.Resampling.LANCZOS)
 pack('margem-direita',rgb,alpha,{'plant':[x,y,w,h],'sourcePlant':[x,y,w,h],'foot':630,'layer':'ground'})
 for name,box in [('solo-reparo',(792,482,816,506)),('rocha-reparo',(1292,515,1316,539))]:
  x,y,x2,y2=box;w,h=x2-x,y2-y
  rgb=source.transform((w*2,h*2),Image.Transform.EXTENT,(x*kx,y*ky,x2*kx,y2*ky),Image.Resampling.BICUBIC)
  # Material frames are inset inside transparent atlas gutters.
  pack(name,rgb,Image.new('L',rgb.size,255),{'plant':[x,y,w,h],'foot':y2,'layer':'material'})
 atlas=atlas.crop((0,0,2048,cy+rowh+8));a=np.array(atlas);a[a[:,:,3]==0]=0;Image.fromarray(a).save(OUT/'refino.png',optimize=True)
 m['version']=2;m['baseFrames']=base
 m['sheets']=[s for s in m['sheets'] if s['id']!='docas_encaixe_refino']+[{'id':'docas_encaixe_refino','src':'assets/sprites/docas-encaixe/refino.png','size':list(atlas.size)}]
 m['refinement']={'method':'Native source resampling + restrained unsharp mask; no AI super-resolution','pieces':NAMES,'newGround':'margem-direita','materials':['solo-reparo','rocha-reparo']}
 (OUT/'manifest.json').write_text(json.dumps(m,ensure_ascii=False,indent=2)+'\n')
 js='// Generated by preparar-docas-encaixe.py + refinar-docas-cirurgico.py. Presentation only.\n'
 js+='export const SPRITES_ENCAIXE='+json.dumps([{k:s[k] for k in ['id','src']} for s in m['sheets']])+';\n'
 js+='export const PECAS_ENCAIXE='+json.dumps(m['frames'],ensure_ascii=False)+';\n'
 (ROOT/'js/data/worlds/arquipelago-rotas-perdidas/docas-encaixe.js').write_text(js)
 print('Refino: 1 new RGBA atlas, 5 restored cutouts + east ground apron; 4 atlases total.')
if __name__=='__main__':main()
